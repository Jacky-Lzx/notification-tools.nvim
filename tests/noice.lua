local h = dofile("tests/helpers.lua")
vim.opt.runtimepath:append(assert(vim.env.NOTIFICATION_TOOLS_NOICE_ROOT))
vim.opt.runtimepath:append(assert(vim.env.NOTIFICATION_TOOLS_NUI_ROOT))
local tools = require("notification-tools")
tools.setup({ notify = false, timeout = 0 })
local views = dofile("examples/noice.lua")
require("noice.config").setup({ views = views })
local view = require("noice.view").get_view("notify", views.notify)
assert(view, "Noice must resolve the consumer-side adapter")
local Message = require("noice.message")
local message = Message("lsp", "message", "LSP warning through Noice")
message.level = "warn"
message.opts = { title = "texquill", id = 7 }
view:push(message, { format = false })
view:show()
h.eq(1, #tools.history())
h.eq("texquill", tools.history()[1].title)
h.eq(vim.log.levels.WARN, tools.history()[1].level)
message = Message("lsp", "message", "Updated warning")
message.opts = { id = 7 }
view:push(message, { format = false })
view:show()
h.eq(1, #tools.history())
h.eq("Updated warning", tools.history()[1].message)
tools.teardown()
print("noice: real Noice/NUI consumer adapter, warning and replacement passed")
